//! ST-058-R2 tables2.1/2.3/2.4 and ST-169 §3.2, independent guest vectors.
use saturn_rust::{Boot, Machine, bus::Memory};
fn rom() -> Vec<u8> {
    let mut rom = vec![0; 524288];
    for line in include_str!("fixtures/display-modes.hex")
        .lines()
        .filter(|l| !l.starts_with('#'))
    {
        let mut fields = line.split_whitespace();
        let at = usize::from_str_radix(fields.next().unwrap(), 16).unwrap();
        for (i, word) in fields.enumerate() {
            rom[at + i * 2..at + i * 2 + 2]
                .copy_from_slice(&u16::from_str_radix(word, 16).unwrap().to_be_bytes());
        }
    }
    rom
}
#[test]
fn original_guest_programs_tv_modes_samples_both_ports_and_observes_fields() {
    // Literal source lines/dimensions and counter encodings, not generated by
    // the implementation. NTSC does not support the PAL-only 256-line modes.
    for pal in [false, true] {
        for (vbits, lines) in [(0u16, 224), (0x10, 240), (0x20, 256)] {
            if !pal && lines == 256 {
                continue;
            }
            for (hbits, width) in [(0, 320), (1, 352), (2, 640), (3, 704)] {
                for (interlace, height) in [(0, lines), (0x80, lines), (0xc0, lines * 2)] {
                    let mode = 0x8000 | vbits | hbits | interlace;
                    let mut rom = rom();
                    rom[0x100..0x102].copy_from_slice(&mode.to_be_bytes());
                    let mut m = Machine::new();
                    m.set_pal(pal);
                    m.reset(Boot::ExternalBios(&rom)).unwrap();
                    m.set_buttons((1 << 0) | (1 << 4) | (1 << 12));
                    m.set_port2_buttons((1 << 3) | (1 << 7) | (1 << 11));
                    m.set_analog(1, Some([0, 128, 255]));
                    for _ in 0..60 {
                        m.run_steps(10000).unwrap();
                        if m.bus().read32(0x0600e088) == Ok(0x600d) {
                            break;
                        }
                    }
                    let r: Vec<_> = (0..35)
                        .map(|i| m.bus().read32(0x0600e000 + i * 4).unwrap())
                        .collect();
                    assert_eq!(
                        r[34],
                        0x600d,
                        "mode={mode:X},pal={pal},pc={:X}",
                        m.cpu_state().pc
                    );
                    assert!(r[1] < 24); // measured first collection just after VBlank-out
                    let counter_scale = if interlace == 0xc0 { 2 } else { 1 };
                    let optimized_line = r[15] / counter_scale;
                    assert!(
                        (lines as u32 - 18..lines as u32 - 12).contains(&optimized_line),
                        "{mode:X}: {optimized_line}"
                    );
                    for base in [0, 14] {
                        assert_eq!(r[base + 2], 0xc0);
                        assert_eq!(
                            &r[base + 3..base + 14],
                            &[0xf1, 2, 0xee, 0xf7, 0xf1, 0x15, 0x77, 0x7f, 0, 128, 255]
                        );
                    }
                    for base in [28, 31] {
                        assert_eq!(r[base] & 9, 8 | u32::from(pal));
                        assert_eq!(r[base + 2] / counter_scale, lines as u32);
                    }
                    assert_eq!(r[28] & 2 == r[31] & 2, interlace == 0);
                    assert_eq!(r[30] & 1 == r[33] & 1, interlace != 0xc0);
                    assert_eq!(m.video_dimensions(), (width, height));
                    let f = m.framebuffer().unwrap();
                    assert_eq!(f.len(), width * height * 4);
                    for y in [0, height - 1] {
                        for (x, color) in [
                            (0, [255, 0, 0, 255]),
                            (1, [0, 255, 0, 255]),
                            (2, [0, 0, 255, 255]),
                            (3, [255, 255, 255, 255]),
                        ] {
                            assert_eq!(
                                &f[(y * width + x) * 4..][..4],
                                color,
                                "mode={mode:X},({x},{y})"
                            );
                        }
                    }
                    if width >= 640 {
                        assert_eq!(&f[511 * 4..][..4], [255, 0, 255, 255]);
                        assert_eq!(&f[512 * 4..][..4], [255, 0, 0, 255]);
                    }
                    // Video standard is a board strap, retained across reset.
                    m.reset(Boot::HlePrototype).unwrap();
                    assert_eq!(m.bus().read16(0x25f80004).unwrap() & 1, u16::from(pal));
                }
            }
        }
    }
}
